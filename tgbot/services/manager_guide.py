_NUMBERS = ("1️⃣", "2️⃣", "3️⃣", "4️⃣", "5️⃣", "6️⃣")


def install_caption(*, title: str = "📲 <b>Покажите клиенту этот QR</b>") -> str:
    """Подпись к QR установки в боте: разворачиваете телефон к клиенту — и по шагам."""
    steps = "\n".join(f"{_NUMBERS[i]} {step}" for i, step in enumerate(INSTALL_STEPS))
    return f"{title}\n\n{steps}"


def section(key: str) -> GuideSection | None:
    return next((s for s in GUIDE if s.key == key), None)
